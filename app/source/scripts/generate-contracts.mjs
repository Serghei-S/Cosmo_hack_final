import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const contracts=path.resolve(root,'../contracts');
const schema=JSON.parse(await readFile(path.join(contracts,'production-event.schema.json'),'utf8'));
const policy=JSON.parse(await readFile(path.join(contracts,'workflow-policy.json'),'utf8'));
const hash=createHash('sha256').update(JSON.stringify({schema,policy})).digest('hex');
function type(s) {
  if(s.$ref) return type(schema.$defs[s.$ref.split('/').at(-1)]);
  if(s.enum) return s.enum.map(v=>JSON.stringify(v).replaceAll('"',"'")).join(' | ');
  if(Array.isArray(s.type)) return s.type.map(t=>type({...s,type:t})).join(' | ');
  if(s.type==='object') return s.properties ? `{ ${Object.entries(s.properties).map(([k,v])=>`${k}${s.required?.includes(k)?'':'?'}: ${type(v)}`).join('; ')} }` : 'Record<string, unknown>';
  if(s.type==='array') return `Array<${type(s.items ?? {})}>`;
  return {string:'string',integer:'number',number:'number',boolean:'boolean',null:'null'}[s.type] ?? 'unknown';
}
const files={
  'src/generated/contracts.ts': `// Generated by orbita-contracts/1.0.0. Do not edit. Source SHA256: ${hash}\nexport type ProductionEventContract = ${type(schema)};\nexport type WorkflowCommandName = ${[...new Set(Object.values(policy.roles).flat())].map(v=>`'${v}'`).join(' | ')};\n`,
  'server/contracts.generated.mjs': `// Generated by orbita-contracts/1.0.0. Do not edit.\nexport const contractHash = '${hash}';\nexport const actionRoles = ${JSON.stringify(policy.roles,null,2).replaceAll('"',"'")};\n`,
};
for(const [name,content] of Object.entries(files)) {
  const file=path.join(root,name);
  if(process.argv.includes('--check')) {
    if(await readFile(file,'utf8')!==content) throw new Error(`Stale generated contract: ${name}. Run pnpm contracts:generate`);
  } else {await mkdir(path.dirname(file),{recursive:true});await writeFile(file,content);}
}
process.stdout.write(`Contracts ${process.argv.includes('--check')?'verified':'generated'}: ${hash}\n`);
